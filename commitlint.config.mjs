const subjectSpanish = ({ subject }) => {
  if (!subject) return [true];
  const firstWord = subject.trim().split(/\s+/)[0].toLowerCase();
  return [
    !ENGLISH_VERBS.has(firstWord),
    `la descripción debe estar en español: usa "agrega", "corrige", "actualiza"... en lugar de "${firstWord}"`,
  ];
};

const config = {
  extends: ["@commitlint/config-conventional"],
  plugins: [{ rules: { "subject-spanish": subjectSpanish } }],
  rules: {
    "subject-case": [0],
    "subject-spanish": [2, "always"],
  },
};

export default config;
